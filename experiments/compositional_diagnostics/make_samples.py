"""Writes samples/families_sample.md: the first test family of every question type in all four arms, for review."""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import questions as Q  # noqa: E402
import render  # noqa: E402


def main() -> int:
    data = HERE / 'data' / 'cd-v0'
    rows = {arm: [json.loads(l) for l in (data / f'test_{arm}.jsonl').read_text().splitlines()] for arm in render.ARMS}
    out = ['# Sample families (test split, first family of each question type)', '',
           'Generated by `make_samples.py` from `data/cd-v0`. Each member shows the instruction, the expected answer, '
           'what the answer must do relative to the base, and the records in all four arms.', '']
    for qtype in Q.QTYPES:
        fam = f'test-{qtype}-0000'
        out += [f'## {qtype}: `{fam}`', '']
        members = [i for i, r in enumerate(rows['json']) if r['family'] == fam]
        for i in members:
            r = rows['json'][i]
            out += [f'### {r["variant"]} (answer must: {r["expect"]})', '', f'Instruction: {r["instruction"]}', '',
                    f'Answer: `{r["answer"]}`', '']
            for arm in render.ARMS:
                out += [f'{arm}:', '', '```', rows[arm][i]['records'].rstrip('\n'), '```', '']
    (HERE / 'samples').mkdir(exist_ok=True)
    (HERE / 'samples' / 'families_sample.md').write_text('\n'.join(out))
    print('wrote samples/families_sample.md')
    return 0


if __name__ == '__main__':
    sys.exit(main())
