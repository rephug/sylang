"""A working agent-to-agent task handoff, measured end to end.

    python -I demo_handoff.py --source <packet> --tokenizer <qwen3 tokenizer.json> \
        --design v2 --k 12345678 --items-per-k 8 \
        --checkpoint sylang2=<compact dev-best .pt> --checkpoint english=<english dev-best .pt> \
        --out results/demo_handoff.json --examples results/demo_handoff_examples.txt

**The workflow.** A *producer* agent holds a batch of status records in its own structure
(Python dicts: subject, relation, object, polarity, tense, aspect, evidence; "w7k will not
have helped q2m"). It hands the batch to a *consumer* agent with one request: list the
negated records as ``[subject, object]`` pairs in order, so a downstream tool can act on
them. The consumer is the packet's tiny byte model trained on the handoff format (one model
per format, from ``language.py``); its answer is parsed back into a list of pairs. For the
Sylang formats the receiver also decodes the message itself back into records with
``sylang_batch.decode`` and the demo checks that the round trip is lossless.

**What is measured, per handoff and per format** (``english``: controlled English;
``sylang2``: header-free Sylang v2; ``sylang1``: Sylang v1 with its header; ``json``: compact
JSON; ``csv``):

1. *conversion in*: producer records -> message text (seconds; the Sylang formats go through
   ``sylang_batch.encode``, and for ``sylang1`` the text is checked byte-for-byte against the
   packet's own renderer);
2. *transport*: the message's bytes and its tokens under the intended deployment tokenizer
   (Qwen 3; the request wording is part of the message);
3. *consumer*: the trained byte model's greedy answer with the packet's reference decoder
   (one full forward per generated byte; seconds), its correctness against the expected
   pairs, and the analytic FLOPs of prefill plus a KV-cached decode;
4. *conversion out*: answer text -> list of pairs (``json.loads``; a parse failure is counted),
   and message -> records for the machine formats (seconds, lossless or not);
5. *whole process*: message tokens + answer tokens (what a deployed model would consume),
   summed over the batch of handoffs, and the wall-clock of stages 1, 3 and 4 together.

Formats without a ``--checkpoint`` are measured on stages 1, 2 and 4 only. Items are fresh
synthetic records from the test split (``language.ItemStream`` for ``--design v2``,
``study3.ItemStream3`` for ``--design v3``, where the six request wordings are cycled and the
held-out wordings are reported separately). Only aggregates and synthetic worked examples
are written.
"""

from __future__ import annotations

import os

os.environ.setdefault('OMP_NUM_THREADS', '1')
os.environ.setdefault('MKL_NUM_THREADS', '1')
os.environ.setdefault('TOKENIZERS_PARALLELISM', 'false')

import argparse  # noqa: E402
import json  # noqa: E402
import statistics  # noqa: E402
import sys  # noqa: E402
import time  # noqa: E402
from collections import defaultdict  # noqa: E402
from pathlib import Path  # noqa: E402

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import language as L  # noqa: E402
import study3  # noqa: E402
import sylang_batch  # noqa: E402
from followup import Runtime  # noqa: E402
from tokens import Counter, _limit_threads  # noqa: E402

FORMATS = ('english', 'sylang2', 'sylang1', 'json', 'csv')
FIELDS = sylang_batch.FIELDS


def _records(statements) -> list[dict]:
    """The producer's native structure: plain dicts with the seven fields."""
    return [{f: s[f] for f in FIELDS} for s in statements]


class Producer:
    """Holds records; converts them into the handoff message of a format."""

    def __init__(self, renderer: L.Renderer):
        self.renderer = renderer

    def handoff(self, records: list[dict], fmt: str, instruction: str) -> tuple[str, float]:
        started = time.perf_counter()
        if fmt == 'sylang2':
            body = sylang_batch.encode(records, version=2)
        elif fmt == 'sylang1':
            body = sylang_batch.encode(records, version=1)
        elif fmt == 'json':
            body = '[' + ','.join(study3._json_record(r) for r in records) + ']\n'
        elif fmt == 'csv':
            body = ''.join(','.join(r[f] for f in ('subject', 'relation', 'polarity', 'tense', 'aspect', 'evidence',
                                                   'object')) + '\n' for r in records)
        elif fmt == 'english':  # the packet's English renderer takes its statement structure
            body = self.renderer.payload('english', [L._statement(*(r[f] for f in FIELDS)) for r in records])
        else:
            raise ValueError(fmt)
        message = body + instruction
        return message, time.perf_counter() - started


class Receiver:
    """Parses a handoff message back into records without any model (machine formats only)."""

    @staticmethod
    def parse(message: str, fmt: str, instruction: str) -> tuple[list[dict] | None, float]:
        body = message[:len(message) - len(instruction)]
        started = time.perf_counter()
        if fmt in ('sylang1', 'sylang2'):
            records, _ = sylang_batch.decode(body)
        elif fmt == 'json':
            records = [{**{f: sylang_batch.DEFAULTS.get(f) for f in FIELDS}, 'subject': o['s'], 'relation': o['r'],
                        'object': o['o'], 'polarity': 'negative' if o.get('neg') else 'positive',
                        **{name: o[key] for key, name in (('t', 'tense'), ('a', 'aspect'), ('e', 'evidence')) if key in o}}
                       for o in json.loads(body)]
            records = [{f: r[f] for f in FIELDS} for r in records]
        elif fmt == 'csv':
            records = [dict(zip(('subject', 'relation', 'polarity', 'tense', 'aspect', 'evidence', 'object'),
                                line.split(','))) for line in body.split('\n') if line]
            records = [{f: r[f] for f in FIELDS} for r in records]
        else:
            return None, 0.0  # English has no parser: that is the point of a machine format
        return records, time.perf_counter() - started


class Consumer:
    """A trained byte model that answers the request in one format."""

    def __init__(self, rt: Runtime, path: str):
        self.rt = rt
        name = Path(path).name
        self.model = rt.load(rt.build(0), path).eval()
        if '-alibi' in name:
            L.use_alibi(self.model, rt.recipe['heads'], rt.tiny.PAD)
        self.name = name
        self.width, self.layers, self.vocab = rt.recipe['width'], rt.recipe['layers'], rt.tiny.VOCAB

    def answer(self, message: str, max_new: int) -> dict:
        started = time.perf_counter()
        out = self.rt.decode.complete(self.model, message, backend='reference', context=self.rt.recipe['context'],
                                      max_new_tokens=max_new, max_seconds=120)
        seconds = time.perf_counter() - started
        text = out['answer'] if out['status'] == 'complete' else None
        prefix = len(message) + 2  # BOS + bytes + SEP
        generated = (len(text) + 1) if text is not None else max_new
        flops = L._flops(prefix, self.layers, self.width, self.vocab) + sum(
            L._flops_cached_step(prefix + i, self.layers, self.width, self.vocab) for i in range(generated))
        return dict(text=text, status=out['status'], seconds=seconds, gflops_prefill_plus_cached_decode=flops / 1e9)


def parse_answer(text: str | None) -> tuple[list | None, float]:
    started = time.perf_counter()
    try:
        pairs = json.loads(text) if text is not None else None
        if pairs is not None and not (isinstance(pairs, list) and all(isinstance(p, list) and len(p) == 2 for p in pairs)):
            pairs = None
    except ValueError:
        pairs = None
    return pairs, time.perf_counter() - started


def items_for(design: str, k_values, per_k: int, seed: int) -> list[tuple[list, str, bool]]:
    """(statements, instruction, wording_held_out) per handoff."""
    out = []
    if design == 'v2':
        stream = L.ItemStream('test', seed, k_values=tuple(k_values), design='v2')
        for k in k_values:
            for _ in range(per_k):
                out.append((stream.item(k), L.INSTRUCTION, False))
    else:
        wordings = study3.WORDINGS['train'] + study3.WORDINGS['heldout']
        stream = study3.ItemStream3('test', seed, k_values=tuple(k_values), wordings=wordings)
        for k in k_values:
            for i in range(per_k):
                w = wordings[i % len(wordings)]
                out.append((stream.item(k, w), w, w in study3.WORDINGS['heldout']))
    return out


def run(args) -> dict:
    _limit_threads()
    rt = Runtime(args.source)
    renderer = L.Renderer(rt)
    counter = Counter(args.tokenizer)
    producer = Producer(renderer)
    consumers = {}
    for spec in args.checkpoint or []:
        fmt, path = spec.split('=', 1)
        if fmt not in FORMATS:
            raise ValueError(fmt)
        consumers[fmt] = Consumer(rt, path)
    k_values = [int(c) for c in (args.k.split(',') if ',' in args.k else args.k)]
    handoffs = items_for(args.design, k_values, args.items_per_k, args.seed)
    rows: dict[str, list[dict]] = defaultdict(list)
    examples = []
    for index, (statements, instruction, held_out_wording) in enumerate(handoffs):
        records = _records(statements)
        expected = [[r['subject'], r['object']] for r in records if r['polarity'] == 'negative']
        expected_text = renderer.target(statements)
        answer_tokens = counter.tokens(expected_text)
        max_new = 4 + sum(len(r['subject']) + len(r['object']) + 8 for r in records)
        example = {'k': len(records), 'expected': expected_text, 'formats': {}}
        for fmt in FORMATS:
            message, t_in = producer.handoff(records, fmt, instruction)
            if fmt == 'sylang1':  # the independent codec against the packet's own renderer
                assert message == renderer.payload('codes', statements) + instruction, 'sylang1 parity'
            parsed, t_parse = Receiver.parse(message, fmt, instruction)
            lossless = None if parsed is None else parsed == records
            row = dict(k=len(records), held_out_wording=held_out_wording, negatives=len(expected),
                       message_bytes=len(message), message_tokens=counter.tokens(message),
                       answer_tokens=answer_tokens, seconds_in=t_in, seconds_parse=t_parse, lossless=lossless)
            if fmt in consumers:
                reply = consumers[fmt].answer(message, max_new)
                pairs, t_out = parse_answer(reply['text'])
                row.update(consumer_seconds=reply['seconds'], consumer_status=reply['status'],
                           gflops=reply['gflops_prefill_plus_cached_decode'], seconds_out=t_out,
                           parse_failed=pairs is None, correct=(pairs == expected),
                           exact_text=(reply['text'] == expected_text))
                example['formats'][fmt] = dict(message=message, answer=reply['text'], correct=pairs == expected,
                                               tokens=row['message_tokens'])
            else:
                example['formats'][fmt] = dict(message=message, tokens=row['message_tokens'])
            rows[fmt].append(row)
        if index < args.n_examples:
            examples.append(example)
    report = {'config': dict(design=args.design, k_values=k_values, items_per_k=args.items_per_k, seed=args.seed,
                             handoffs=len(handoffs), tokenizer_sha256_prefix=counter.sha256,
                             consumers={fmt: c.name for fmt, c in consumers.items()},
                             decoder='packet reference decoder, one full forward per generated byte, 1 thread',
                             flops='analytic: prefill of the message + KV-cached decode of the answer')}
    for fmt in FORMATS:
        r = rows[fmt]
        agg = dict(n=len(r),
                   message_tokens_mean=round(statistics.fmean(x['message_tokens'] for x in r), 2),
                   message_tokens_total=sum(x['message_tokens'] for x in r),
                   message_bytes_mean=round(statistics.fmean(x['message_bytes'] for x in r), 1),
                   answer_tokens_mean=round(statistics.fmean(x['answer_tokens'] for x in r), 2),
                   process_tokens_total=sum(x['message_tokens'] + x['answer_tokens'] for x in r),
                   seconds_in_mean=round(statistics.fmean(x['seconds_in'] for x in r), 6),
                   seconds_parse_mean=round(statistics.fmean(x['seconds_parse'] for x in r), 6),
                   lossless_round_trips=sum(bool(x['lossless']) for x in r) if r[0]['lossless'] is not None else None,
                   by_k={k: dict(message_tokens=round(statistics.fmean(x['message_tokens'] for x in r if x['k'] == k), 2))
                         for k in k_values})
        if fmt in consumers:
            agg.update(accuracy=round(statistics.fmean(x['correct'] for x in r), 4),
                       exact_text=round(statistics.fmean(x['exact_text'] for x in r), 4),
                       parse_failures=sum(x['parse_failed'] for x in r),
                       incomplete=sum(x['consumer_status'] != 'complete' for x in r),
                       consumer_seconds_mean=round(statistics.fmean(x['consumer_seconds'] for x in r), 4),
                       consumer_seconds_by_k={k: round(statistics.fmean(x['consumer_seconds'] for x in r if x['k'] == k), 4)
                                              for k in k_values},
                       gflops_mean=round(statistics.fmean(x['gflops'] for x in r), 4),
                       process_seconds_mean=round(statistics.fmean(x['seconds_in'] + x['consumer_seconds'] + x['seconds_out']
                                                                   + x['seconds_parse'] for x in r), 4),
                       accuracy_by_k={k: round(statistics.fmean(x['correct'] for x in r if x['k'] == k), 4) for k in k_values})
            if args.design == 'v3':
                for flag, name in ((False, 'trained_wording'), (True, 'held_out_wording')):
                    sub = [x for x in r if x['held_out_wording'] == flag]
                    if sub:
                        agg[f'accuracy_{name}'] = round(statistics.fmean(x['correct'] for x in sub), 4)
        report[fmt] = agg
    for fmt in FORMATS:
        if fmt != 'english':
            report[fmt]['process_tokens_ratio_to_english'] = round(
                report[fmt]['process_tokens_total'] / report['english']['process_tokens_total'], 4)
    return report, examples


def markdown(report: dict) -> str:
    head = ['format', 'consumer', 'accuracy', 'message tok (mean)', 'answer tok', 'process tok (total)', 'ratio to english',
            'conversion in (ms)', 'consumer (s)', 'parse out (ms)', 'lossless']
    lines = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    for fmt in FORMATS:
        r = report[fmt]
        lines.append('| ' + ' | '.join([
            fmt, 'yes' if 'accuracy' in r else 'no (tokens only)',
            f"{100 * r['accuracy']:.1f}%" if 'accuracy' in r else '–',
            f"{r['message_tokens_mean']:.1f}", f"{r['answer_tokens_mean']:.1f}", f"{r['process_tokens_total']:,}",
            f"{r.get('process_tokens_ratio_to_english', 1.0):.2f}", f"{1000 * r['seconds_in_mean']:.3f}",
            f"{r['consumer_seconds_mean']:.3f}" if 'consumer_seconds_mean' in r else '–',
            f"{1000 * r['seconds_parse_mean']:.3f}" if r['lossless_round_trips'] is not None else '–',
            f"{r['lossless_round_trips']}/{r['n']}" if r['lossless_round_trips'] is not None else 'n/a']) + ' |')
    return '\n'.join(lines)


def write_examples(examples: list[dict], path: str) -> None:
    out = []
    for n, ex in enumerate(examples, 1):
        out.append(f"=== handoff {n} (K={ex['k']}); expected answer: {ex['expected']}")
        for fmt, d in ex['formats'].items():
            out.append(f"--- {fmt} message ({len(d['message'])} bytes, {d['tokens']} Qwen 3 tokens)")
            out.append(d['message'].rstrip('\n'))
            if 'answer' in d:
                out.append(f"consumer answer: {d['answer']}  [{'correct' if d['correct'] else 'WRONG'}]")
        out.append('')
    Path(path).write_text('\n'.join(out))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source', required=True)
    parser.add_argument('--tokenizer', required=True)
    parser.add_argument('--design', default='v2', choices=('v2', 'v3'))
    parser.add_argument('--k', default='12345678', help='record counts: digits, or comma-separated for K > 9')
    parser.add_argument('--items-per-k', type=int, default=8)
    parser.add_argument('--seed', type=int, default=23)
    parser.add_argument('--checkpoint', action='append', help='format=path, e.g. sylang2=<dev-best .pt>')
    parser.add_argument('--n-examples', type=int, default=2)
    parser.add_argument('--out', required=True)
    parser.add_argument('--examples', help='text file of worked examples (synthetic identifiers)')
    args = parser.parse_args()
    report, examples = run(args)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(report, indent=1, sort_keys=True) + '\n')
    print(markdown(report))
    if args.examples:
        write_examples(examples, args.examples)


if __name__ == '__main__':
    main()
